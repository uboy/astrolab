def get_zodiac_sign(month: int, day: int) -> tuple[str, str]:
    """
    Вернуть название и эмодзи знака зодиака по месяцу и дню.
    """
    zodiac = [
        ((1, 20), (2, 18), "Водолей", "♒"),
        ((2, 19), (3, 20), "Рыбы", "♓"),
        ((3, 21), (4, 19), "Овен", "♈"),
        ((4, 20), (5, 20), "Телец", "♉"),
        ((5, 21), (6, 20), "Близнецы", "♊"),
        ((6, 21), (7, 22), "Рак", "♋"),
        ((7, 23), (8, 22), "Лев", "♌"),
        ((8, 23), (9, 22), "Дева", "♍"),
        ((9, 23), (10, 22), "Весы", "♎"),
        ((10, 23), (11, 21), "Скорпион", "♏"),
        ((11, 22), (12, 21), "Стрелец", "♐"),
        ((12, 22), (12, 31), "Козерог", "♑"),
        ((1, 1), (1, 19), "Козерог", "♑"),  # январский диапазон Козерога
    ]

    for start, end, name, emoji in zodiac:
        sm, sd = start
        em, ed = end
        if (month == sm and day >= sd) or (month == em and day <= ed) or (sm < month < em):
            return name, emoji

    return "Неопределён", "✨"
