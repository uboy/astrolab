def get_zodiac(day: int, month: int) -> str:
    zodiac_dates = [
        ((21, 3), (19, 4), "Овен"),
        ((20, 4), (20, 5), "Телец"),
        ((21, 5), (20, 6), "Близнецы"),
        ((21, 6), (22, 7), "Рак"),
        ((23, 7), (22, 8), "Лев"),
        ((23, 8), (22, 9), "Дева"),
        ((23, 9), (22, 10), "Весы"),
        ((23, 10), (21, 11), "Скорпион"),
        ((22, 11), (21, 12), "Стрелец"),
        ((22, 12), (19, 1), "Козерог"),
        ((20, 1), (18, 2), "Водолей"),
        ((19, 2), (20, 3), "Рыбы"),
    ]
    for start, end, sign in zodiac_dates:
        if (month == start[1] and day >= start[0]) or (month == end[1] and day <= end[0]):
            return sign
    return "Неизвестно"
